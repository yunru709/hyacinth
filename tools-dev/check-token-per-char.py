# -*- coding: utf-8 -*-
"""复核 token/字 判据：中文自然语速是否稳定落在 4~6 token/字？

1 speech token = 40 ms ⇒ tok/字 = dur * 25 / 字数
把所有历史样本（包含各轮坏样本）拉进来，看正常带与坏样本是否真的分得开。
"""
samples = {
    '3字':  (2,  [0.64, 0.80, 1.36, 1.36, 1.84, 0.96, 0.32, 1.28, 0.72, 0.52]),
    '6字':  (4,  [0.60, 1.48, 2.72, 4.28, 0.64, 2.32, 0.48, 3.00, 0.68, 1.92, 2.00, 0.08]),
    '12字': (10, [1.92, 2.08, 2.08, 2.04, 3.96, 2.72, 2.48, 3.84, 1.56, 9.60]),
    '20字': (18, [3.80, 4.40, 4.72, 4.40, 15.32, 6.68, 5.12, 8.84, 4.16, 6.40]),
    '21字': (19, [4.52, 5.20, 5.60, 3.52, 2.72, 4.20, 5.08, 8.48, 5.84, 6.52, 16.80, 7.68]),
    '37字': (35, [7.92, 7.96, 9.48, 8.76, 9.04, 8.84, 8.00, 9.44, 11.84]),
}

LO, HI = 3.2, 8.0

print('=== 各长度 token/字 分布（括号内为被拒收的离群值）===')
for lab, (cjk, vals) in samples.items():
    tp = [v * 25.0 / cjk for v in vals]
    ok = ['%.1f' % t for t in tp if LO <= t <= HI]
    bad = ['%.2fs->%.1f' % (v, t) for v, t in zip(vals, tp) if not (LO <= t <= HI)]
    print('%-5s cjk=%2d  正常[%s]' % (lab, cjk, ' '.join(ok)))
    print('             拒收[%s]' % ' '.join(bad))

print()
print('=== 判据边界自检 ===')
print('LO=%.1f HI=%.1f  (中文自然 4~6 ⇒ 两侧各留约 1.3 倍余量)' % (LO, HI))
